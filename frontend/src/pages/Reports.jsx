import { useEffect, useState } from "react";
import toast from "react-hot-toast";
import { deleteReport, generateReport, listReports, reportUrl } from "../services/api";
import { ErrorState } from "../components/ErrorState";
import { EmptyState } from "../components/EmptyState";
import { formatBytes } from "../utils/format";

const REPORT_OPTIONS = [
  { id: "metrics", label: "Include performance metrics" },
  { id: "processes", label: "Include process analysis" },
  { id: "hardware", label: "Include hardware inventory" },
  { id: "diagnosis", label: "Include AI diagnosis" },
  { id: "recommendations", label: "Include recommendations" },
];

export function Reports({ ai, online, onRetry }) {
  const [reports, setReports] = useState([]);
  const [busy, setBusy] = useState(false);
  const [options, setOptions] = useState(() => Object.fromEntries(REPORT_OPTIONS.map((item) => [item.id, true])));

  async function refresh() {
    try {
      setReports(await listReports());
    } catch {
      setReports([]);
    }
  }

  useEffect(() => {
    let cancelled = false;
    async function load() {
      try {
        const items = await listReports();
        if (!cancelled) setReports(items);
      } catch {
        if (!cancelled) setReports([]);
      }
    }
    if (online) load();
    return () => {
      cancelled = true;
    };
  }, [online]);

  async function createReport() {
    setBusy(true);
    try {
      const data = await generateReport();
      if (!data.success) {
        toast.error(data.message || "Failed to generate report");
        return;
      }
      toast.success("Report generated");
      await refresh();
    } catch (error) {
      toast.error(error.response?.data?.message || "Failed to generate report");
    } finally {
      setBusy(false);
    }
  }

  async function remove(filename) {
    try {
      await deleteReport(filename);
      toast.success("Report deleted");
      await refresh();
    } catch {
      toast.error("Could not delete report");
    }
  }

  return (
    <div className="page">
      {!online ? <ErrorState title="Backend unavailable" body="PDF reports are generated by the local engine." onRetry={onRetry} /> : null}

      <div className="page-head row">
        <div>
          <h1>Reports</h1>
          <p>PDF health documents with live metrics, process snapshot, and diagnosis from this PC.</p>
        </div>
        <button type="button" className="btn btn-primary" onClick={createReport} disabled={busy || !online}>
          {busy ? "Generating…" : "Generate new report"}
        </button>
      </div>

      <section className="panel panel-pad">
        {reports.length === 0 ? (
          <EmptyState title="No report yet" body="Generate a report to open the latest system document." />
        ) : (
          reports.map((item) => (
            <div className="report-row" key={item.filename}>
              <div>
                <strong>System health report</strong>
                <div className="muted" style={{ marginTop: 4 }}>
                  {new Date(item.created).toLocaleString()} · {formatBytes(item.size)} · Health {ai?.health_score ?? "—"}/100
                </div>
              </div>
              <div className="row" style={{ justifyContent: "flex-end" }}>
                <a className="btn" href={reportUrl(item.filename)} target="_blank" rel="noreferrer">View</a>
                <a className="btn" href={reportUrl(item.filename)} download>Download</a>
                <button type="button" className="btn btn-danger" onClick={() => remove(item.filename)}>Delete</button>
              </div>
            </div>
          ))
        )}
      </section>

      <section className="panel panel-pad">
        <div className="section-title">Report settings</div>
        <p className="muted" style={{ marginTop: 4 }}>The generated PDF always includes live telemetry. These options record your preferred sections.</p>
        <div style={{ marginTop: 8 }}>
          {REPORT_OPTIONS.map((item) => (
            <label className="check-row" key={item.id}>
              <span>
                <input
                  type="checkbox"
                  checked={options[item.id]}
                  onChange={() => setOptions((prev) => ({ ...prev, [item.id]: !prev[item.id] }))}
                />
                {" "}
                {item.label}
              </span>
            </label>
          ))}
        </div>
      </section>
    </div>
  );
}
