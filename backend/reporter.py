from datetime import datetime
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)


REPORT_DIR = Path("reports")
REPORT_DIR.mkdir(exist_ok=True)


def generate_report(metrics, ai):

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")

    filename = REPORT_DIR / f"SMARTPULSE_Report_{timestamp}.pdf"

    doc = SimpleDocTemplate(str(filename))

    styles = getSampleStyleSheet()

    title = styles["Heading1"]
    title.alignment = TA_CENTER

    heading = styles["Heading2"]

    normal = styles["BodyText"]

    story = []

    story.append(
        Paragraph(
            "SMARTPULSE AI Performance Report",
            title
        )
    )

    story.append(
        Paragraph(
            datetime.now().strftime("%d %B %Y %H:%M:%S"),
            normal
        )
    )

    story.append(Spacer(1, 20))

    # ===========================
    # HEALTH
    # ===========================

    story.append(
        Paragraph(
            "Overall Health",
            heading
        )
    )

    health_table = Table([

        ["Health Score",
         ai["health_score"]],

        ["Severity",
         ai["severity"]]

    ])

    health_table.setStyle(

        TableStyle([

            ("GRID",(0,0),(-1,-1),1,colors.grey),

            ("BACKGROUND",(0,0),(-1,0),colors.HexColor("#0ea5e9")),

            ("TEXTCOLOR",(0,0),(-1,0),colors.white),

            ("BACKGROUND",(0,1),(-1,-1),colors.whitesmoke),

            ("BOTTOMPADDING",(0,0),(-1,-1),8)

        ])

    )

    story.append(health_table)

    story.append(Spacer(1,20))

    # ===========================
    # LIVE METRICS
    # ===========================

    story.append(
        Paragraph(
            "Current System Metrics",
            heading
        )
    )

    metric_table = Table([

        ["Metric","Value"],

        ["CPU Usage",f'{metrics["cpu"]}%'],

        ["RAM Usage",f'{metrics["ram"]}%'],

        ["GPU Usage",f'{metrics["gpu"]}%'],

        ["Disk Usage",f'{metrics["disk"]}%'],

        ["CPU Frequency",
         f'{metrics["cpu_frequency"]} MHz'],

        ["Upload Speed",
         f'{metrics["upload_speed"]} MB/s'],

        ["Download Speed",
         f'{metrics["download_speed"]} MB/s']

    ])

    metric_table.setStyle(

        TableStyle([

            ("GRID",(0,0),(-1,-1),1,colors.grey),

            ("BACKGROUND",(0,0),(-1,0),colors.HexColor("#16a34a")),

            ("TEXTCOLOR",(0,0),(-1,0),colors.white),

            ("BOTTOMPADDING",(0,0),(-1,-1),8)

        ])

    )

    story.append(metric_table)

    story.append(Spacer(1,20))

    # ===========================
    # HARDWARE
    # ===========================

    story.append(

        Paragraph(

            "Hardware",

            heading

        )

    )

    hardware = Table([

        ["CPU",metrics["cpu_name"]],

        ["GPU",metrics["gpu_name"]],

        ["RAM",

         f'{metrics["total_ram_gb"]} GB'],

        ["Disk Free",

         f'{metrics["disk_free_gb"]} GB'],

        ["Physical Cores",

         metrics["physical_cores"]],

        ["Logical Cores",

         metrics["logical_cores"]]

    ])

    hardware.setStyle(

        TableStyle([

            ("GRID",(0,0),(-1,-1),1,colors.grey),

            ("BACKGROUND",(0,0),(-1,0),colors.HexColor("#7c3aed")),

            ("TEXTCOLOR",(0,0),(-1,0),colors.white)

        ])

    )

    story.append(hardware)

    story.append(Spacer(1,20))

    # ===========================
    # AI ALERTS
    # ===========================

    story.append(

        Paragraph(

            "AI Analysis",

            heading

        )

    )

    for alert in ai["alerts"]:

        story.append(

            Paragraph(

                f"• {alert}",

                normal

            )

        )

    story.append(Spacer(1,20))

    story.append(

        Paragraph(

            "<b>Generated by SMARTPULSE AI v2</b>",

            normal

        )

    )

    doc.build(story)

    return str(filename)